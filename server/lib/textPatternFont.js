// 모르는 글자는 그냥 빈 공간(A-Z/0-9와 같은 폭 4)으로 보여준다.
const BLANK_GLYPH = ['0000', '0000', '0000', '0000', '0000'];

function getGlyph(char) {
  const key = char.toUpperCase();
  return FONT[key] || BLANK_GLYPH;
}

